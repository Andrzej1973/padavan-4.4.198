const assert = require('node:assert/strict');
const make = require('./wifi-qr-payload.js');
const base = {ssid: 'Home', auth: 'psk', wep: '0', password: 'password', hidden: false};
assert.equal(make(base).payload, 'WIFI:T:WPA;S:Home;P:password;H:false;;');
assert.equal(make({...base, hidden: true}).payload, 'WIFI:T:WPA;S:Home;P:password;H:true;;');
assert.equal(make({...base, auth: 'open'}).payload, 'WIFI:T:nopass;S:Home;H:false;;');
assert.equal(make({...base, auth: 'open', wep: '1'}).error, 'security');
for (const auth of ['wpa', 'wpa2', 'radius', 'shared']) assert.equal(make({...base, auth}).error, 'security');
assert.equal(make({...base, ssid: 'a;:,"\\'}).payload, 'WIFI:T:WPA;S:a\\;\\:\\,\\"\\\\;P:password;H:false;;');
assert.equal(make({...base, ssid: 'a'.repeat(32)}).error, undefined);
assert.equal(make({...base, ssid: 'a'.repeat(33)}).error, 'ssid');
assert.equal(make({...base, ssid: 'ї'.repeat(16)}).error, undefined);
assert.equal(make({...base, ssid: 'ї'.repeat(17)}).error, 'ssid');
assert.equal(make({...base, password: 'short'}).error, 'password');
assert.equal(make({...base, password: 'a'.repeat(63)}).error, undefined);
assert.equal(make({...base, password: 'a'.repeat(64)}).error, 'password');
assert.equal(make({...base, ssid: '\ud800'}).error, 'encoding');
assert.equal(make({...base, ssid: 'Home\n'}).error, 'ssid');
assert.equal(make({...base, password: 'pass\nword'}).error, 'password');
console.log('PASS: local Wi-Fi QR payload escaping, UTF-8 limits, hidden/open/personal and unsupported modes');
