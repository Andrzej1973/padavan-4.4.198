#!/usr/bin/env python3
"""Prepare current queue and later recovery chain; no production installation.

Open fragments are generated by default; historical comparison is optional.
This remains a partial source candidate, not a buildable module.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('source',type=Path,help='Exact pinned mt76x3 source tree')
p.add_argument('reviewed_open',type=Path,nargs='?',help='Optional hash-reviewed historical comparison')
p.add_argument('output',type=Path,help='New separate workspace')
a=p.parse_args()
source=a.source.resolve(strict=True)
reviewed=a.reviewed_open.resolve(strict=True) if a.reviewed_open else None
out=a.output.resolve()
if out.exists() or any(x==out or x in out.parents or out in x.parents for x in (source,reviewed) if x is not None):
    p.error('output must be new and separate from inputs')
expected={'common/cmm_cfg.c':'5d0eb4c4057dd485d9c15d1bfdea69a6744ffb3461c0624590b191904d7ea388',
          'include/rt_os_net.h':'bc362d748229d88e8482547139956f2fa80727e9aa87903d30904396c1e43471'}
if reviewed is not None:
    for name,digest in expected.items():
        if hashlib.sha256((reviewed/name).read_bytes()).hexdigest()!=digest:
            p.error('reviewed open input mismatch: '+name)
out.mkdir(parents=True)
here=Path(__file__).resolve().parent
steps=[]
for script,args in (
 ('prepare-radio-queue-candidate.py',[source,out/'queue']),
 ('prepare-queue-main-open-compose.py',[out/'queue/driver',*([reviewed] if reviewed else []),out/'main-open']),
 ('prepare-later-recovery-chain.py',[out/'main-open',out/'later','--input-stage','main-open',
   '--prior-manifest',out/'main-open-composition.json','--source-tree',source])):
    result=subprocess.run([sys.executable,str(here/script),*map(str,args)],
                          capture_output=True,text=True,timeout=600)
    (out/(script+'.log')).write_text(result.stdout+result.stderr,encoding='utf-8')
    steps.append({'script':script,'returncode':result.returncode,
                  'sha256':hashlib.sha256((here/script).read_bytes()).hexdigest()})
    if result.returncode:
        raise SystemExit('Failed '+script+'; see '+str(out))
receipt=json.loads((out/'later/chain.json').read_text())
(out/'preparation.json').write_text(json.dumps({'steps':steps,
 'reviewed_open_sha256':expected,'candidate_sha256':receipt['candidate_sha256'],
 'historical_open_dependency_remaining':False, 'historical_comparison_used':reviewed is not None,'complete_driver_tree':False,
 'target_compiled':False,'production_installed':False,'runtime_verified':False},indent=2)+'\n')
print('PASS current queue/recovery preparation; generated open fragments used unless comparison requested')
