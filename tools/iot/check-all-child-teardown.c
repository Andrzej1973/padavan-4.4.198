#include "all-child-teardown.h"
#include "mbss-retirement.h"
#include <assert.h>
int main(void){
 struct wr_child_teardown t;
 struct wr_bss_retirement bss[2];
 wr_bss_retirement_init(&bss[0]);wr_bss_retirement_init(&bss[1]);
 assert(wr_bss_retirement_publish(&bss[0],1));
 assert(wr_bss_retirement_publish(&bss[1],2));
 wr_child_teardown_init(&t);
 assert(!wr_child_teardown_begin(&t,WR_CHILD_ALL,0));
 assert(!wr_child_teardown_begin(&t,16U,1));
 assert(wr_child_teardown_begin(&t,WR_CHILD_ALL,1));
 assert(!wr_child_teardown_may_free_adapter(&t,1));
 assert(!wr_child_teardown_complete(&t,WR_CHILD_APCLI));
 assert(!wr_child_teardown_close_done(&t,WR_CHILD_APCLI,0));
 assert(wr_child_teardown_close_done(&t,WR_CHILD_APCLI,1));
 assert(wr_child_teardown_complete(&t,WR_CHILD_APCLI));
 assert(!wr_child_teardown_abort_unmutated(&t,1));
 assert(wr_child_teardown_close_done(&t,WR_CHILD_WDS,1));
 assert(wr_child_teardown_complete(&t,WR_CHILD_WDS));
 wr_child_teardown_fail(&t);
 assert(t.phase==WR_CHILD_POISONED);
 assert(!wr_child_teardown_begin(&t,WR_CHILD_ALL,1));
 assert(!wr_child_teardown_complete(&t,WR_CHILD_MBSS));
 assert(!wr_child_teardown_may_free_adapter(&t,1));
 wr_child_teardown_init(&t);
 assert(wr_child_teardown_begin(&t,WR_CHILD_MBSS,1));
 assert(!wr_child_teardown_abort_unmutated(&t,0));
 assert(wr_child_teardown_abort_unmutated(&t,1));
 assert(wr_child_teardown_begin(&t,WR_CHILD_ALL,1));
 assert(!wr_child_teardown_complete(&t,WR_CHILD_MBSS|WR_CHILD_MONITOR));
 assert(wr_child_teardown_close_done(&t,WR_CHILD_APCLI,1));
 assert(wr_child_teardown_complete(&t,WR_CHILD_APCLI));
 assert(wr_child_teardown_close_done(&t,WR_CHILD_WDS,1));
 assert(wr_child_teardown_complete(&t,WR_CHILD_WDS));
 assert(!wr_bss_retirement_family_done(bss,2));
 assert(wr_bss_retirement_begin(&bss[0],1,1));
 assert(wr_bss_retirement_beacon_done(&bss[0],1));
 assert(wr_bss_retirement_kernel_done(&bss[0],1));
 assert(wr_bss_retirement_vendor_done(&bss[0],1));
 assert(!wr_bss_retirement_family_done(bss,2));
 assert(wr_bss_retirement_begin(&bss[1],2,1));
 assert(wr_bss_retirement_beacon_done(&bss[1],2));
 assert(wr_bss_retirement_kernel_done(&bss[1],2));
 assert(wr_bss_retirement_vendor_done(&bss[1],2));
 assert(wr_bss_retirement_family_done(bss,2));
 assert(!wr_child_teardown_complete(&t,WR_CHILD_MBSS));
 assert(wr_child_teardown_close_done(&t,WR_CHILD_MBSS,1));
 assert(wr_child_teardown_complete(&t,WR_CHILD_MBSS));
 assert(!wr_child_teardown_complete(&t,WR_CHILD_MBSS));
 assert(!wr_child_teardown_may_free_adapter(&t,1));
 assert(wr_child_teardown_close_done(&t,WR_CHILD_MONITOR,1));
 assert(wr_child_teardown_complete(&t,WR_CHILD_MONITOR));
 assert(!wr_child_teardown_may_free_adapter(&t,0));
 assert(wr_child_teardown_may_free_adapter(&t,1));
 wr_child_teardown_init(&t);
 assert(wr_child_teardown_begin(&t,0,1));
 assert(!wr_child_teardown_may_free_adapter(&t,0));
 assert(wr_child_teardown_may_free_adapter(&t,1));
 return 0;
}
